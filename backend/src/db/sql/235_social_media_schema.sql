CREATE TABLE IF NOT EXISTS post_comments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  post_id INT NOT NULL,
  platform ENUM('facebook','instagram','x') NOT NULL,
  external_comment_id VARCHAR(255) NOT NULL,
  parent_comment_id VARCHAR(255),
  author_name VARCHAR(255),
  author_id VARCHAR(255),
  message TEXT NOT NULL,
  ai_reply_draft TEXT,
  ai_reply_status ENUM('pending','approved','rejected','sent'),
  ai_reply_model VARCHAR(100),
  ai_reply_provider VARCHAR(100),
  ai_replied_tweet_id VARCHAR(64),
  like_count INT DEFAULT 0,
  created_time DATETIME(3),
  fetched_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY post_comments_uuid_unique (uuid),
  UNIQUE KEY uk_pc_post_platform_ext (post_id, platform, external_comment_id),
  KEY idx_pc_post (post_id),
  CONSTRAINT fk_pc_post FOREIGN KEY (post_id) REFERENCES social_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS post_analytics (
  id INT AUTO_INCREMENT PRIMARY KEY,
  post_id INT NOT NULL,
  platform ENUM('facebook','instagram','x','youtube') NOT NULL,
  likes INT DEFAULT 0,
  comments INT DEFAULT 0,
  shares INT DEFAULT 0,
  saves INT DEFAULT 0,
  reach INT DEFAULT 0,
  impressions INT DEFAULT 0,
  clicks INT DEFAULT 0,
  engagement_rate DECIMAL(5,2) DEFAULT '0',
  fetched_at DATETIME(3) NOT NULL,
  KEY idx_pan_post (post_id),
  KEY idx_pan_platform (platform),
  KEY idx_pan_fetched (fetched_at),
  CONSTRAINT fk_pan_post FOREIGN KEY (post_id) REFERENCES social_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS campaign_calendar (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  tenant_key VARCHAR(100) NOT NULL DEFAULT 'goldmoodastro',
  date DATE NOT NULL,
  time_slot ENUM('morning','afternoon','evening') NOT NULL DEFAULT 'morning',
  post_type ENUM('haber','etkilesim','ilan','nostalji','tanitim','kampanya') NOT NULL,
  platform ENUM('facebook','instagram','both','linkedin','x','telegram','all','youtube') NOT NULL DEFAULT 'both',
  notes TEXT,
  template_id INT,
  post_id INT,
  status ENUM('planned','content_ready','scheduled','published','skipped') DEFAULT 'planned',
  created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY campaign_calendar_uuid_unique (uuid),
  UNIQUE KEY uk_cc_slot (tenant_key, date, time_slot, platform),
  CONSTRAINT fk_cc_template FOREIGN KEY (template_id) REFERENCES content_templates(id) ON DELETE SET NULL,
  CONSTRAINT fk_cc_post FOREIGN KEY (post_id) REFERENCES social_posts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS x_api_usage (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usage_month CHAR(7) NOT NULL,
  operation ENUM('write','read') NOT NULL,
  count INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_xau_month_op (usage_month, operation)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
