CREATE TABLE IF NOT EXISTS content_templates (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  tenant_key VARCHAR(100),
  name VARCHAR(255) NOT NULL,
  post_type ENUM('haber','etkilesim','ilan','nostalji','tanitim','kampanya') NOT NULL,
  platform ENUM('facebook','instagram','both','linkedin','x','telegram','all','youtube') NOT NULL DEFAULT 'both',
  caption_template TEXT NOT NULL,
  hashtags VARCHAR(500),
  image_prompt VARCHAR(500),
  variables JSON,
  is_active TINYINT DEFAULT 1,
  usage_count INT DEFAULT 0,
  last_used_at DATETIME,
  created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY content_templates_uuid_unique (uuid),
  KEY idx_ct_post_type (post_type),
  KEY idx_ct_active (is_active),
  KEY idx_ct_tenant (tenant_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS social_posts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid CHAR(36) NOT NULL,
  post_type ENUM('haber','etkilesim','ilan','nostalji','tanitim','kampanya') NOT NULL,
  sub_type VARCHAR(50),
  title VARCHAR(255),
  caption TEXT NOT NULL,
  hashtags VARCHAR(500),
  image_url VARCHAR(1000),
  image_local VARCHAR(500),
  link_url VARCHAR(1000),
  link_text VARCHAR(255),
  platform ENUM('facebook','instagram','both','linkedin','x','telegram','all','youtube') NOT NULL DEFAULT 'both',
  fb_page_id VARCHAR(100),
  ig_account_id VARCHAR(100),
  scheduled_at DATETIME,
  posted_at DATETIME,
  status ENUM('draft','scheduled','publishing','manual_pending','posted','failed','cancelled') NOT NULL DEFAULT 'draft',
  error_message VARCHAR(1000),
  fb_post_id VARCHAR(255),
  ig_media_id VARCHAR(255),
  x_tweet_id VARCHAR(64),
  youtube_video_id VARCHAR(64),
  postproxy_post_id VARCHAR(64),
  x_thread_group CHAR(36),
  x_thread_order INT,
  x_reply_to_tweet_id VARCHAR(64),
  media_urls JSON,
  auto_edit_job_id VARCHAR(64),
  auto_edit_status ENUM('queued','processing','done','failed','approved'),
  auto_edit_transcript TEXT,
  auto_edit_segments JSON,
  auto_edit_error TEXT,
  source_type ENUM('manual','news','ai','template') NOT NULL DEFAULT 'manual',
  source_ref VARCHAR(255),
  ai_generated TINYINT DEFAULT 0,
  ai_model VARCHAR(100),
  ai_prompt_used TEXT,
  created_by VARCHAR(100) DEFAULT 'system',
  notes TEXT,
  created_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY social_posts_uuid_unique (uuid),
  KEY idx_sp_status (status),
  KEY idx_sp_scheduled (scheduled_at),
  KEY idx_sp_platform (platform),
  KEY idx_sp_post_type (post_type),
  KEY idx_sp_source (source_type),
  KEY idx_sp_youtube (youtube_video_id),
  KEY idx_sp_x_thread (x_thread_group),
  KEY idx_sp_subtype (sub_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

